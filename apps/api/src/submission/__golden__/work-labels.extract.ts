export type WorkLabel = Readonly<{ label: string; from: readonly string[] }>

/** The file text of `work-labels.json`. */
export function extractWorkLabels(): string {
  const seen = new Map<string, Set<string>>()
  const add = (label: string, from: string) => {
    const set = seen.get(label) ?? new Set<string>()
    set.add(from)
    seen.set(label, set)
  }
  for (const source of LABEL_SOURCES) {
    for (const literal of stringLiterals(readFileSync(`${REPO}${source}`, "utf8"))) {
      if (looksLikeLabel(literal)) add(literal, source)
    }
  }
  for (const label of EXTRA_LABELS) add(label, "extra")
  const labels: WorkLabel[] = [...seen].map(([label, from]) => ({ label, from: [...from] }))
  return `${JSON.stringify({ note: "EPIC-0002 A0 work-question labels. Generated by work-labels.extract.ts.", sources: LABEL_SOURCES, labels }, null, 2)}\n`
}

function looksLikeLabel(text: string): boolean {
  if (text.length < 8 || text.length > 300) return false
  if (/[<>{}=_%]|^\s|\s$|\n/.test(text)) return false
  // A form label starts with a capital letter and has more than one word; test titles start lower case.
  if (!/^\p{Lu}/u.test(text) || !text.includes(" ")) return false
  return WORK_LIKE.test(text)
}

/** Every string and template literal, with `${NAME}` replaced for the known template constants. */
function stringLiterals(code: string): string[] {
  const scanner = ts.createScanner(ts.ScriptTarget.Latest, false, ts.LanguageVariant.Standard, code)
  const out: string[] = []
  // One frame per open template literal: its text so far (null once an expression is not a known constant),
  // the tokens of the current `${...}` expression and the brace depth inside it.
  const frames: { text: string | null; expression: string[]; depth: number }[] = []
  for (let token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken; token = scanner.scan()) {
    const frame = frames.at(-1)
    if (token === ts.SyntaxKind.TemplateHead) {
      frame?.expression.push("`")
      frames.push({ text: scanner.getTokenValue(), expression: [], depth: 0 })
      continue
    }
    if (frame && token === ts.SyntaxKind.OpenBraceToken) frame.depth += 1
    if (frame && token === ts.SyntaxKind.CloseBraceToken) {
      if (frame.depth > 0) {
        frame.depth -= 1
      } else {
        const part = scanner.reScanTemplateToken(false)
        const name = frame.expression.length === 1 ? frame.expression[0] : undefined
        const value = name !== undefined ? TEMPLATE_CONSTANTS[name] : undefined
        frame.text = frame.text === null || value === undefined ? null : frame.text + value + scanner.getTokenValue()
        frame.expression = []
        if (part === ts.SyntaxKind.TemplateTail) {
          frames.pop()
          if (frame.text !== null) out.push(frame.text)
        }
        continue
      }
    }
    if (token === ts.SyntaxKind.StringLiteral || token === ts.SyntaxKind.NoSubstitutionTemplateLiteral) out.push(scanner.getTokenValue())
    frame?.expression.push(token === ts.SyntaxKind.Identifier ? scanner.getTokenValue() : String(token))
  }
  return out
}
